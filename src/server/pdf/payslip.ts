import "server-only";
import type { Breakdown } from "@/domain/hr/payroll";
import { A4, Doc, fmtAmount, M, MUTED } from "./kit";

export async function payslipPdf(p: { name: string; employeeNo: string; jobTitle: string; unit: string; month: string; bank: string | null; breakdown: Breakdown; deductionLines: { reason: string; amount: number }[] }): Promise<Uint8Array> {
  const monthName = new Intl.DateTimeFormat("en-GB", { month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(`${p.month}-15T00:00:00Z`));
  const d = await Doc.create(`Payslip ${p.employeeNo} ${p.month}`);
  d.header(p.unit, "PAYSLIP");
  const right = A4.w - M;
  const kv = (k: string, v: string) => {
    d.text(k, M, { size: 9, color: MUTED });
    d.text(v, M + 110, { size: 10 });
    d.y -= 15;
  };
  kv("Employee", p.name);
  kv("Employee no.", p.employeeNo);
  kv("Role", p.jobTitle);
  kv("Pay period", monthName);
  if (p.bank) kv("Paid to", p.bank);
  if (p.breakdown.proRata < 1) kv("Part month", `${Math.round(p.breakdown.proRata * 100)}% of working days`);
  d.y -= 10;

  const section = (title: string, rows: { name: string; amount: number }[], sign = "") => {
    if (!rows.length) return;
    d.ensure(20 + rows.length * 16);
    d.text(title.toUpperCase(), M, { size: 8, bold: true, color: MUTED });
    d.y -= 6;
    d.rule();
    d.y -= 14;
    for (const r of rows) {
      d.text(r.name, M, { size: 10 });
      d.text(`${sign}${fmtAmount(r.amount, "NGN")}`, right, { size: 10, align: "right" });
      d.y -= 16;
    }
    d.y -= 6;
  };
  section("Earnings", [{ name: "Basic pay", amount: p.breakdown.base }, ...p.breakdown.allowances, ...p.breakdown.bonuses]);
  d.text("Gross pay", M, { bold: true });
  d.text(fmtAmount(p.breakdown.gross, "NGN"), right, { bold: true, align: "right" });
  d.y -= 24;
  section("Statutory", p.breakdown.statutory, "-");
  section("Deductions", p.breakdown.deductions, "-");
  d.rule();
  d.y -= 20;
  d.text("Net pay", M, { size: 13, bold: true });
  d.text(fmtAmount(p.breakdown.net, "NGN"), right, { size: 13, bold: true, align: "right" });
  d.y -= 30;
  if (p.deductionLines.length) {
    d.text("LATENESS & ABSENCE DETAIL", M, { size: 8, bold: true, color: MUTED });
    d.y -= 14;
    for (const l of p.deductionLines) {
      d.ensure(14);
      d.para(`${l.reason} - ${fmtAmount(l.amount, "NGN")}`, M, A4.w - 2 * M, { size: 8.5, color: MUTED });
    }
  }
  d.footer(["Confidential. Generated by Figuraid OS. Query any line with HR within 7 days of payment.", "Approved excuses, leave and public holidays are never deducted."]);
  return d.bytes();
}
