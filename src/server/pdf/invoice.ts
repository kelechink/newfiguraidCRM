import "server-only";
import { A4, Doc, fmtAmount, fmtDate, LINE, M, MUTED } from "./kit";

export interface InvoicePdfInput {
  kind: "INVOICE" | "QUOTE" | "CREDIT_NOTE";
  number: string;
  unitName: string;
  issueDate: Date;
  dueDate: Date;
  currency: string;
  billTo: { name: string; company?: string | null; email?: string | null; phone?: string | null };
  period?: { start: Date; end: Date } | null;
  lines: { description: string; quantity: number; unitPrice: number; amount: number }[];
  subtotal: number;
  vatRate: number;
  vatAmount: number;
  total: number;
  amountPaid: number;
  notes?: string | null;
  payLink?: string | null;
  bankInstructions?: string | null;
}

export async function invoicePdf(i: InvoicePdfInput): Promise<Uint8Array> {
  const title = i.kind === "QUOTE" ? "QUOTE" : i.kind === "CREDIT_NOTE" ? "CREDIT NOTE" : "INVOICE";
  const d = await Doc.create(`${title} ${i.number}`);
  d.header(i.unitName, title);

  // meta block
  const right = A4.w - M;
  const meta: [string, string][] = [
    ["Number", i.number],
    ["Issued", fmtDate(i.issueDate)],
    [i.kind === "QUOTE" ? "Valid until" : "Due", fmtDate(i.dueDate)],
    ...(i.period ? ([["Period", `${fmtDate(i.period.start)} - ${fmtDate(i.period.end)}`]] as [string, string][]) : []),
  ];
  const top = d.y;
  d.text("BILL TO", M, { size: 8, bold: true, color: MUTED });
  d.y -= 14;
  d.text(i.billTo.company || i.billTo.name, M, { size: 11, bold: true });
  d.y -= 13;
  if (i.billTo.company) {
    d.text(i.billTo.name, M, { size: 9.5 });
    d.y -= 12;
  }
  for (const l of [i.billTo.email, i.billTo.phone].filter(Boolean) as string[]) {
    d.text(l, M, { size: 9.5, color: MUTED });
    d.y -= 12;
  }
  const leftBottom = d.y;
  d.y = top;
  for (const [k, v] of meta) {
    d.text(k, right - 150, { size: 9, color: MUTED });
    d.text(v, right, { size: 9.5, align: "right", bold: k === "Number" });
    d.y -= 14;
  }
  d.y = Math.min(d.y, leftBottom) - 18;

  // table
  const cols = { desc: M, qty: right - 210, price: right - 110, amt: right };
  const head = () => {
    d.text("DESCRIPTION", cols.desc, { size: 8, bold: true, color: MUTED });
    d.text("QTY", cols.qty, { size: 8, bold: true, color: MUTED, align: "right" });
    d.text("UNIT PRICE", cols.price, { size: 8, bold: true, color: MUTED, align: "right" });
    d.text("AMOUNT", cols.amt, { size: 8, bold: true, color: MUTED, align: "right" });
    d.y -= 8;
    d.rule();
    d.y -= 14;
  };
  head();
  for (const l of i.lines) {
    d.ensure(30);
    const y0 = d.y;
    d.para(l.description, cols.desc, cols.qty - 70 - cols.desc, { size: 9.5 });
    const after = d.y;
    d.y = y0;
    d.text(l.quantity.toLocaleString("en-NG", { maximumFractionDigits: 4 }), cols.qty, { size: 9.5, align: "right" });
    d.text(l.unitPrice.toLocaleString("en-NG", { maximumFractionDigits: 6 }), cols.price, { size: 9.5, align: "right" });
    d.text(fmtAmount(l.amount, i.currency), cols.amt, { size: 9.5, align: "right" });
    d.y = after - 4;
    d.rule(LINE);
    d.y -= 14;
  }

  // totals
  d.ensure(90);
  const row = (k: string, v: string, bold = false) => {
    d.text(k, right - 150, { size: bold ? 10.5 : 9.5, bold, color: bold ? undefined : MUTED });
    d.text(v, right, { size: bold ? 10.5 : 9.5, bold, align: "right" });
    d.y -= bold ? 18 : 14;
  };
  row("Subtotal", fmtAmount(i.subtotal, i.currency));
  if (i.vatAmount > 0) row(`VAT (${i.vatRate}%)`, fmtAmount(i.vatAmount, i.currency));
  row("Total", fmtAmount(i.total, i.currency), true);
  if (i.amountPaid > 0) {
    row("Paid", `- ${fmtAmount(i.amountPaid, i.currency)}`);
    row("Balance due", fmtAmount(Math.max(0, i.total - i.amountPaid), i.currency), true);
  }

  d.y -= 10;
  if (i.payLink) {
    d.text("PAY ONLINE", M, { size: 8, bold: true, color: MUTED });
    d.y -= 13;
    d.para(i.payLink, M, A4.w - 2 * M, { size: 9 });
    d.y -= 6;
  }
  if (i.bankInstructions) {
    d.text("BANK TRANSFER", M, { size: 8, bold: true, color: MUTED });
    d.y -= 13;
    d.para(i.bankInstructions, M, A4.w - 2 * M, { size: 9 });
    d.y -= 6;
  }
  if (i.notes) {
    d.text("NOTES", M, { size: 8, bold: true, color: MUTED });
    d.y -= 13;
    d.para(i.notes, M, A4.w - 2 * M, { size: 9, color: MUTED });
  }
  d.footer(["Figuraid Ltd · Abuja, Nigeria · finance@figuraid.com", `${title} ${i.number} · generated by Figuraid OS`]);
  return d.bytes();
}
