// Builds the dot-matrix world map for the homepage coverage section.
// Run: node scripts/site/build-world-dots.mjs  → src/components/site/world-dots.ts
// Uses Natural Earth land (world-atlas, public domain); output is static, no runtime map code.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoContains, geoNaturalEarth1 } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-50m.json"), "utf8"));
const land = feature(topo, topo.objects.land);

const W = 1000, H = 500, STEP = 9;
const projection = geoNaturalEarth1().fitExtent([[10, 10], [W - 10, H - 10]], { type: "Sphere" });

function region(lon, lat) {
  if (lon < -25) return "americas";
  if (lat >= 12 && lat <= 42 && lon >= 34 && lon <= 63) return "middleEast";
  if (lat >= 35 && lon >= -25 && lon < 45) return "europe";
  if (lat < 37 && lon >= -20 && lon < 52) return "africa";
  return "asiaPacific";
}

const paths = { americas: [], europe: [], africa: [], middleEast: [], asiaPacific: [] };
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const ll = projection.invert([x, y]);
    if (!ll || !Number.isFinite(ll[0])) continue;
    const back = projection(ll);
    if (!back || Math.abs(back[0] - x) > 0.5 || Math.abs(back[1] - y) > 0.5) continue; // outside the sphere
    if (ll[1] < -58) continue; // leave Antarctica out
    if (!geoContains(land, ll)) continue;
    paths[region(ll[0], ll[1])].push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}
const out = `// Generated by scripts/site/build-world-dots.mjs — do not edit by hand.
export const WORLD_VIEWBOX = "0 0 ${W} ${H}";
export const WORLD_DOTS = ${JSON.stringify(Object.fromEntries(Object.entries(paths).map(([k, v]) => [k, v.join("")])))} as const;
`;
writeFileSync("src/components/site/world-dots.ts", out);
console.log(Object.fromEntries(Object.entries(paths).map(([k, v]) => [k, v.length])), `${(out.length / 1024).toFixed(0)} KB`);
